/**
 * Runtime shims for old WebKit (iOS 9 / Safari 9, e.g. first-gen iPad mini).
 *
 * Imported first in main.tsx. Every shim is feature-detected, so on modern
 * browsers this file only costs a few feature checks. Syntax and standard
 * library polyfills (Promise, Map, Object.entries, ...) come from
 * @vitejs/plugin-legacy / core-js, not from here.
 */
import ResizeObserverPolyfill from 'resize-observer-polyfill'

/* eslint-disable @typescript-eslint/no-explicit-any, prefer-rest-params, prefer-spread */
const w = window as any

// ── ResizeObserver (Safari < 13.1) — used by react-grid-layout & dnd-kit ──
if (!w.ResizeObserver) w.ResizeObserver = ResizeObserverPolyfill

// ── Path2D (Safari < 10) — TrackMap caches track outlines as Path2D ──────
if (typeof w.Path2D === 'undefined' && w.CanvasRenderingContext2D) {
  const OPS = [
    'moveTo', 'lineTo', 'closePath', 'rect', 'arc', 'arcTo',
    'bezierCurveTo', 'quadraticCurveTo', 'ellipse',
  ]
  const P2D: any = function (this: any) { this._ops = [] }
  OPS.forEach((m) => {
    P2D.prototype[m] = function (this: any) {
      this._ops.push([m, Array.prototype.slice.call(arguments)])
    }
  })
  w.Path2D = P2D

  const proto = w.CanvasRenderingContext2D.prototype
  ;['fill', 'stroke', 'clip'].forEach((m) => {
    const orig = proto[m]
    proto[m] = function (this: any, a?: any, b?: unknown) {
      if (a instanceof P2D) {
        this.beginPath()
        for (let i = 0; i < a._ops.length; i++) {
          this[a._ops[i][0]].apply(this, a._ops[i][1])
        }
        return b === undefined ? orig.call(this) : orig.call(this, b)
      }
      return orig.apply(this, arguments)
    }
  })
}

// ── Web Audio: prefixed context + callback-only decodeAudioData ───────────
if (!w.AudioContext && w.webkitAudioContext) {
  w.AudioContext = w.webkitAudioContext
  const proto = w.webkitAudioContext.prototype
  const orig = proto.decodeAudioData
  proto.decodeAudioData = function (this: any, data: ArrayBuffer, ok?: unknown, err?: unknown) {
    if (ok) return orig.call(this, data, ok, err)
    return new Promise((resolve, reject) => { orig.call(this, data, resolve, reject) })
  }
}

// ── Flexbox `gap` detection (Safari < 14.1) ───────────────────────────────
// Adds `no-flex-gap` to <html>; CSS fallbacks (generated by
// tools/postcss-flex-gap.mjs + legacy.css) and legacy/jsx-runtime.ts key off it.
function flexGapSupported(): boolean {
  const host = document.body || document.documentElement
  const f = document.createElement('div')
  f.style.cssText = 'display:flex;flex-direction:column;row-gap:1px;position:absolute;visibility:hidden'
  f.appendChild(document.createElement('div'))
  f.appendChild(document.createElement('div'))
  host.appendChild(f)
  const ok = f.scrollHeight === 1
  host.removeChild(f)
  return ok
}
if (!flexGapSupported()) document.documentElement.classList.add('no-flex-gap')
